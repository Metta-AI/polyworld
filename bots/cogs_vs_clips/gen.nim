## Builds player.bas: the fixed FourScore map as DATA arrays, then logic.bas.
## Run: nim r bots/cogs_vs_clips/gen.nim

import std/[algorithm, math, os, strutils]

const
  Width = 120
  Height = 120
  Padded = Width + 2
  CellSize = 10
  Cells = Width div CellSize
  Aligners = 3
  Hubs = [(29, 29), (89, 29), (29, 89), (89, 89)]
  ## Points from each hub toward its own map corner, where sectors split.
  Corners = [(-1, -1), (1, -1), (-1, 1), (1, 1)]
  LocalRadius = 45

type Point = tuple[x, y: int]

proc padded(x, y: int): int =
  ## Returns the index into the walled 122 by 122 grid.
  (y + 1) * Padded + x + 1

proc cell(p: Point): int =
  ## Returns the 10 by 10 bucket that holds a point.
  (p.y div CellSize) * Cells + p.x div CellSize

proc distance2(a, b: Point): int =
  ## Returns squared Euclidean distance.
  (a.x - b.x) ^ 2 + (a.y - b.y) ^ 2

proc dataLine(name: string, values: openArray[int]): string =
  ## Formats one single-line BASIC DATA declaration.
  var parts: seq[string]
  for value in values:
    parts.add $value
  "data " & name & " = " & parts.join(",")

proc buckets(points: seq[Point]): seq[int] =
  ## Returns the first index of each bucket for points sorted by cell.
  result = newSeq[int](Cells * Cells + 1)
  var at = 0
  for c in 0 ..< Cells * Cells:
    result[c] = at
    while at < points.len and points[at].cell == c:
      inc at
  result[^1] = points.len

proc neighborLists(points: seq[Point], radius: int): (seq[int], seq[int]) =
  ## Returns start offsets and the flat list of points within a radius.
  var starts, list: seq[int]
  for i, a in points:
    starts.add list.len
    for j, b in points:
      if i != j and a.distance2(b) <= radius * radius:
        list.add j
  starts.add list.len
  (starts, list)

proc sectors(junctions: seq[Point], team: int): seq[int] =
  ## Splits the junctions near a hub into equal angular aligner sectors.
  let
    hub = (x: Hubs[team][0], y: Hubs[team][1])
    cut = arctan2(float(Corners[team][1]), float(Corners[team][0]))
  proc angle(p: Point): float =
    ## Measures clockwise from the corner direction, in [0, 2 pi).
    var value = arctan2(float(p.y - hub.y), float(p.x - hub.x)) - cut
    while value < 0: value += 2 * PI
    while value >= 2 * PI: value -= 2 * PI
    value
  var near: seq[float]
  for p in junctions:
    if p.distance2(hub) <= LocalRadius * LocalRadius:
      near.add p.angle
  near.sort()
  var bounds: seq[float]
  for s in 1 ..< Aligners:
    bounds.add near[near.len * s div Aligners]
  for p in junctions:
    var sector = 0
    for bound in bounds:
      if p.angle >= bound:
        inc sector
    result.add sector

proc main() =
  let
    root = currentSourcePath().parentDir
    rows = readFile(root / "fourscore.txt").splitLines()
  var
    passable = newSeq[int](Padded * Padded)
    junctions, extractors: seq[Point]
    elements: seq[int]
  for y in 0 ..< Height:
    for x in 0 ..< Width:
      let symbol = rows[y][x]
      case symbol
      of '.', '0' .. '3':
        passable[padded(x, y)] = 1
      of 'j':
        junctions.add (x, y)
      of 'C', 'O', 'G', 'S':
        extractors.add (x, y)
      else:
        discard
  junctions.sort(proc(a, b: Point): int = cmp(a.cell * 100000 + a.y * 1000 + a.x,
    b.cell * 100000 + b.y * 1000 + b.x))
  extractors.sort(proc(a, b: Point): int = cmp(a.cell * 100000 + a.y * 1000 + a.x,
    b.cell * 100000 + b.y * 1000 + b.x))
  for p in extractors:
    elements.add "COGS".find(rows[p.y][p.x])
  var
    junctionTiles, junctionHubs, junctionSectors: seq[int]
    extractorTiles: seq[int]
  for p in junctions:
    junctionTiles.add padded(p.x, p.y)
    var mask = 0
    for team, hub in Hubs:
      if p.distance2((x: hub[0], y: hub[1])) <= 25 * 25:
        mask = mask or (1 shl team)
    junctionHubs.add mask
  for team in 0 ..< Hubs.len:
    junctionSectors.add junctions.sectors(team)
  for p in extractors:
    extractorTiles.add padded(p.x, p.y)
  let (alignStarts, alignList) = junctions.neighborLists(15)
  var xs, ys: seq[int]
  for p in junctions:
    xs.add p.x
    ys.add p.y
  var lines = @[
    "' Cogs vs Clips PW bot. Generated by gen.nim from fourscore.txt and logic.bas.",
    "' Edit logic.bas, then rerun: nim r bots/cogs_vs_clips/gen.nim",
    "junctionCount = " & $junctions.len,
    "extractorCount = " & $extractors.len,
    "alignerCount = " & $Aligners,
    dataLine("passable", passable),
    dataLine("junctionX", xs),
    dataLine("junctionY", ys),
    dataLine("junctionTile", junctionTiles),
    dataLine("junctionHubs", junctionHubs),
    dataLine("junctionSector", junctionSectors),
    dataLine("junctionBucket", junctions.buckets),
    dataLine("alignStart", alignStarts),
    dataLine("alignList", alignList)
  ]
  xs.setLen(0)
  ys.setLen(0)
  for p in extractors:
    xs.add p.x
    ys.add p.y
  lines.add dataLine("extractorX", xs)
  lines.add dataLine("extractorY", ys)
  lines.add dataLine("extractorTile", extractorTiles)
  lines.add dataLine("extractorElement", elements)
  lines.add dataLine("extractorBucket", extractors.buckets)
  let source = lines.join("\n") & "\n" & readFile(root / "logic.bas")
  writeFile(root / "player.bas", source)
  echo "player.bas: ", source.len, " bytes, ", junctions.len, " junctions, ",
    extractors.len, " extractors"

main()
