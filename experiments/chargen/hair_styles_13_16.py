def build(style, hair):
  """Add the assigned concept hairstyle to the shared geometry builder."""
  if style == 13:
    pixie(hair)
  elif style == 14:
    ponytail(hair)
  elif style == 15:
    locs(hair)
  elif style == 16:
    sideBraid(hair)
