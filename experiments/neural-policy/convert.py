"""Extract the supplied v63 policy's literals without changing its game code."""

import argparse
import hashlib
from pathlib import Path
import re


def data(name, kind, rows):
    """Format one row-major DATA array using exact source literal strings."""
    values = [value for row in rows for value in row]
    lines = [f"DATA {name} AS {kind} = _"]
    for offset in range(0, len(values), 6):
        line = "  " + ", ".join(values[offset:offset + 6])
        if offset + 6 < len(values):
            line += ", _"
        lines.append(line)
    return "\n".join(lines) + "\n"


def convert(source):
    """Convert only the three affine layers, ReLU, and score selection."""
    draft_start = source.index("  draftBestClass = -1\n")
    draft_end = source.index("  if draftBestClass >= 0 then\n")
    blocks = re.findall(
        r"  if draftF\((\d+)\) then\n(.*?)\n  end if",
        source[draft_start:draft_end], re.S,
    )
    assert [int(index) for index, _ in blocks] == list(range(10))
    draft_weights, draft_biases = [], []
    for _, body in blocks:
        draft_biases.append(re.search(r"draftScore = (-?[\d.]+)", body)[1])
        terms = re.findall(
            r"draftScore = draftScore \+ draftF\((\d+)\) \* (-?[\d.]+)",
            body,
        )
        indices = [int(index) for index, _ in terms]
        assert indices == sorted(set(indices)) and max(indices) < 32
        row = ["0.000000"] * 32
        for index, value in terms:
            row[int(index)] = value
        draft_weights.append(row)

    encoder_rows = re.findall(r"^h\((\d+)\) = (-?\d+)(.*)$", source, re.M)
    decoder_rows = re.findall(r"^score = (-?\d+)(.*)$", source, re.M)
    assert [int(index) for index, _, _ in encoder_rows] == list(range(16))
    assert len(decoder_rows) == 18
    encoder_weights, encoder_biases = [], []
    decoder_weights, decoder_biases = [], []
    for _, bias, body in encoder_rows:
        terms = re.findall(r"f\((\d+)\) \* \((-?\d+)\)", body)
        assert [int(index) for index, _ in terms] == list(range(25))
        encoder_weights.append([value for _, value in terms])
        encoder_biases.append(bias)
    for bias, body in decoder_rows:
        terms = re.findall(r"h\((\d+)\) \* \((-?\d+)\)", body)
        assert [int(index) for index, _ in terms] == list(range(16))
        decoder_weights.append([value for _, value in terms])
        decoder_biases.append(bias)

    draft = """  linear(draftF, draftWeights, draftBias, draftScores, 32, 10)
  draftBestClass = argmaxMasked(draftScores, draftF, 10)
"""
    source = source[:draft_start] + draft + source[draft_end:]
    start = source.index("h(0) = ")
    end = source.index("\nend if", source.index("  decision = 17\n", start))
    # Keep the END IF for the four-tick inference countdown.
    end = source.index("\nend if", end + 1)
    combat = """  linear(f, encoder, encoderBias, h, 25, 16)
  relu(h, 16)
  linear(h, decoder, decoderBias, logits, 16, 18)
  decision = argmax(logits, 18)
  ' Preserve the original sentinel edge case for int32 wraparound.
  if logits(decision) <= -2147483647 then
    decision = 0
  end if"""
    source = source[:start] + combat + source[end:]
    header = """' Richard's v63 policy using native, metered array arithmetic.
' Generated by convert.py. Game observations and commands are unchanged.
' DATA initializes once. DIM retains its inclusive BASIC upper bound.
' Matrices are row-major: weights(outputIndex * inputCount + inputIndex).

"""
    for name, kind, rows in [
        ("draftWeights", "fixed32", draft_weights),
        ("draftBias", "fixed32", [draft_biases]),
        ("encoder", "int32", encoder_weights),
        ("encoderBias", "int32", [encoder_biases]),
        ("decoder", "int32", decoder_weights),
        ("decoderBias", "int32", [decoder_biases]),
    ]:
        header += data(name, kind, rows) + "\n"
    header += "dim draftScores(9)\ndim logits(17)\n\n"
    return header + source


def main():
    """Convert an unchanged input file and print its provenance digest."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    arguments = parser.parse_args()
    source = arguments.source.read_bytes()
    arguments.destination.write_text(convert(source.decode("utf-8")))
    print("Source SHA-256:", hashlib.sha256(source).hexdigest())


if __name__ == "__main__":
    main()
